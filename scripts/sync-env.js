/**
 * Copies GEMINI_API_KEY from .env into config.local.js (gitignored),
 * because Chrome extensions cannot read .env files at runtime.
 *
 * Usage: npm run sync-env
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'config.local.js');

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

let env = {};
if (fs.existsSync(envPath)) {
  env = parseEnv(fs.readFileSync(envPath, 'utf8'));
} else {
  console.warn('No .env found — copy .env.example to .env and add your key.');
}

const key = env.GEMINI_API_KEY || '';
const contents =
  '// AUTO-GENERATED by scripts/sync-env.js from .env — do not edit or commit.\n' +
  `export const GEMINI_API_KEY = ${JSON.stringify(key)};\n`;

fs.writeFileSync(outPath, contents);
console.log(
  key
    ? 'config.local.js written with GEMINI_API_KEY. Reload the extension in chrome://extensions.'
    : 'config.local.js written, but GEMINI_API_KEY is empty. Fill it in .env and run again.'
);
